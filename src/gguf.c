static ptrdiff_t gguf_reader_left(const gguf_reader *r) {
	return (ptrdiff_t)(r->end - r->p);
}

static int gguf_reader_u8(gguf_reader *r, uint8_t *o) {
	if (gguf_reader_left(r) < (ptrdiff_t)1)
		return -1;
	*o = r->p[0];
	r->p += 1;
	return 0;
}

static int gguf_reader_u16(gguf_reader *r, uint16_t *o) {
	if (gguf_reader_left(r) < (ptrdiff_t)2)
		return -1;
	uint16_t v;
	memcpy(&v, r->p, 2);
	*o = le16toh(v);
	r->p += 2;
	return 0;
}

static int gguf_reader_u32(gguf_reader *r, uint32_t *o) {
	if (gguf_reader_left(r) < (ptrdiff_t)4)
		return -1;
	uint32_t v;
	memcpy(&v, r->p, 4);
	*o = le32toh(v);
	r->p += 4;
	return 0;
}

static int gguf_reader_u64(gguf_reader *r, uint64_t *o) {
	if (gguf_reader_left(r) < (ptrdiff_t)8)
		return -1;
	uint64_t v;
	memcpy(&v, r->p, 8);
	*o = le64toh(v);
	r->p += 8;
	return 0;
}

static int gguf_reader_f32(gguf_reader *r, float *o) {
	uint32_t v;
	if (gguf_reader_u32(r, &v))
		return -1;
	memcpy(o, &v, sizeof(v));
	return 0;
}

static int gguf_reader_f64(gguf_reader *r, double *o) {
	uint64_t v;
	if (gguf_reader_u64(r, &v))
		return -1;
	memcpy(o, &v, sizeof(v));
	return 0;
}

static int gguf_reader_str(gguf_reader *r, gguf_str *o) {
	uint64_t n;
	if (gguf_reader_u64(r, &n))
		return -1;
	if ((uint64_t)gguf_reader_left(r) < n)
		return -1;
	o->len	= n;
	o->data = (const char *)r->p;
	r->p += n;
	return 0;
}

static int gguf_reader_bool(gguf_reader *r, int *o) {
	uint8_t v;
	if (gguf_reader_u8(r, &v))
		return -1;
	*o = v != 0;
	return 0;
}

static int gguf_arr_len_ok(const gguf_reader *r, uint64_t n, size_t elem_size) {
	if (elem_size == 0 || n > (uint64_t)(SIZE_MAX / elem_size))
		return 0;
	return n * (uint64_t)elem_size <= (uint64_t)gguf_reader_left(r);
}

static int gguf_read_numeric_array(gguf_reader *r, kv_entry *e) {
	static const uint8_t sizes[] = {
		[GGUF_TYPE_U8] = 1,	 [GGUF_TYPE_I8] = 1,  [GGUF_TYPE_BOOL] = 1, [GGUF_TYPE_U16] = 2,
		[GGUF_TYPE_I16] = 2, [GGUF_TYPE_U32] = 4, [GGUF_TYPE_I32] = 4,	[GGUF_TYPE_F32] = 4,
		[GGUF_TYPE_U64] = 8, [GGUF_TYPE_I64] = 8, [GGUF_TYPE_F64] = 8,
	};
	size_t width = e->arr_type < ARRAY_LEN(sizes) ? sizes[e->arr_type] : 0;
	if (!gguf_arr_len_ok(r, e->arr_len, width))
		return -1;
	size_t	 bytes = (size_t)e->arr_len * width;
	uint8_t *data  = xmalloc(bytes);
	memcpy(data, r->p, bytes);
	if (__BYTE_ORDER == __BIG_ENDIAN) {
		for (size_t off = 0; off < bytes; off += width) {
			for (size_t i = 0; i < width / 2; i++) {
				uint8_t tmp				  = data[off + i];
				data[off + i]			  = data[off + width - 1 - i];
				data[off + width - 1 - i] = tmp;
			}
		}
	}
	r->p += bytes;
	e->arr_data = data;
	return 0;
}

static int parse_kv_value(gguf_reader *r, kv_entry *e, uint32_t type, str_arena *sa) {
	e->type = type;
	switch (type) {
	case GGUF_TYPE_U8: {
		uint8_t v;
		if (gguf_reader_u8(r, &v))
			return -1;
		e->ival = v;
		return 0;
	}
	case GGUF_TYPE_I8: {
		uint8_t v;
		if (gguf_reader_u8(r, &v))
			return -1;
		e->ival = (unsigned char)(int8_t)v;
		return 0;
	}
	case GGUF_TYPE_U16: {
		uint16_t v;
		if (gguf_reader_u16(r, &v))
			return -1;
		e->ival = v;
		return 0;
	}
	case GGUF_TYPE_I16: {
		uint16_t v;
		if (gguf_reader_u16(r, &v))
			return -1;
		e->ival = (int16_t)v;
		return 0;
	}
	case GGUF_TYPE_U32: {
		uint32_t v;
		if (gguf_reader_u32(r, &v))
			return -1;
		e->ival = v;
		return 0;
	}
	case GGUF_TYPE_I32: {
		uint32_t v;
		if (gguf_reader_u32(r, &v))
			return -1;
		e->ival = (int32_t)v;
		return 0;
	}
	case GGUF_TYPE_U64: {
		uint64_t v;
		if (gguf_reader_u64(r, &v))
			return -1;
		e->ival = v;
		return 0;
	}
	case GGUF_TYPE_I64: {
		uint64_t v;
		if (gguf_reader_u64(r, &v))
			return -1;
		e->ival = (int64_t)v;
		return 0;
	}
	case GGUF_TYPE_F32: {
		float v;
		if (gguf_reader_f32(r, &v))
			return -1;
		e->ival = 0;
		memcpy(&e->ival, &v, 4);
		return 0;
	}
	case GGUF_TYPE_F64: {
		double v;
		if (gguf_reader_f64(r, &v))
			return -1;
		e->ival = 0;
		memcpy(&e->ival, &v, 8);
		return 0;
	}
	case GGUF_TYPE_BOOL: {
		int v;
		if (gguf_reader_bool(r, &v))
			return -1;
		e->ival = v;
		return 0;
	}
	case GGUF_TYPE_STRING: {
		gguf_str s;
		if (gguf_reader_str(r, &s))
			return -1;
		char *owned = str_arena_dup(sa, s.data, s.len);
		e->str.len	= s.len;
		e->str.data = owned;
		return 0;
	}
	case GGUF_TYPE_ARRAY: {
		uint32_t et;
		uint64_t n;
		if (gguf_reader_u32(r, &et))
			return -1;
		if (gguf_reader_u64(r, &n))
			return -1;
		e->arr_type = et;
		e->arr_len	= n;
		if (et == GGUF_TYPE_STRING) {
			if (!gguf_arr_len_ok(r, n, sizeof(char *)))
				return -1;
			char **arr = (char **)xmalloc(n * sizeof(char *));
			for (uint64_t i = 0; i < n; i++) {
				gguf_str s;
				if (gguf_reader_str(r, &s)) {
					free(arr);
					return -1;
				}
				arr[i] = str_arena_dup(sa, s.data, s.len);
			}
			e->arr_data = (void *)arr;
		} else {
			return gguf_read_numeric_array(r, e);
		}
		return 0;
	}
	default:
		return -1;
	}
}

static void free_kv(kv_entry *e, size_t n) {
	for (size_t i = 0; i < n; i++) {
		if (e[i].type == GGUF_TYPE_ARRAY)
			free(e[i].arr_data);
	}
	free(e);
}

